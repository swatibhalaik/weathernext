#!/usr/bin/env python3
"""list_dataset_variables.py -- empirical inventory of every variable actually
present in predictions.nc, the source ERA5 dataset, and the stats/ folder,
cross-referenced against what this reproduction's evaluation scripts already
score.

Why this exists: rather than take my word for "predictions.nc has exactly
84 target channels and all of them are already covered by Tier 1 + Tier 2",
run this and see the real variable names/shapes/dtypes straight from the
files on your machine -- and, as a bonus, find out whether the stats/ files
carry the lat/lon spatial resolution that evaluate_fig3_fig4_fig5_extremes.py
needs (see that script's docstring).

Usage:
    python list_dataset_variables.py --data-dir ./gencast_data \
        --predictions ./gencast_output/predictions.nc
"""
from __future__ import annotations

import argparse
from pathlib import Path

# Variables already scored somewhere in this reproduction (evaluate_predictions.py,
# evaluate_full_scorecard.py Tier 1 + Tier 2). Anything in predictions.nc NOT in
# this set is genuinely unused and worth a second look.
ALREADY_SCORED_SURFACE = {
    "2m_temperature", "mean_sea_level_pressure",
    "10m_u_component_of_wind", "10m_v_component_of_wind",
    "total_precipitation_12hr", "sea_surface_temperature",
}
ALREADY_SCORED_ATMOSPHERIC = {
    "temperature", "geopotential", "u_component_of_wind",
    "v_component_of_wind", "specific_humidity", "vertical_velocity",
}

# Known INPUT-ONLY variables (forcings / static fields) that condition the
# model but are never predicted, so they will never appear in predictions.nc
# even though they exist in the source dataset -- listed here so the report
# below can explain them if found, rather than flag them as a mystery.
KNOWN_FORCING_VARS = {
    "toa_incident_solar_radiation": "Top-of-atmosphere incident solar radiation. "
        "A genuine physical driver of weather (day/night, season) that the model "
        "is TOLD as a known future input at every lead time (it's fully "
        "predictable from orbital mechanics alone) rather than something it has "
        "to forecast. Not a prediction target.",
    "year_progress_sin": "sin(2*pi*fraction of year elapsed) -- an encoding of "
        "calendar season, given to the model as context, not predicted.",
    "year_progress_cos": "cos() counterpart of the above, together giving the "
        "model an unambiguous point on the yearly cycle.",
    "day_progress_sin": "sin(2*pi*fraction of day elapsed) -- time-of-day "
        "encoding (for the diurnal cycle), given as context, not predicted.",
    "day_progress_cos": "cos() counterpart of the above.",
}
KNOWN_STATIC_VARS = {
    "geopotential_at_surface": "Static surface elevation (as geopotential) -- "
        "terrain doesn't change during a 15-day forecast, so it's given once as "
        "a fixed map, not predicted.",
    "land_sea_mask": "Static land/sea/ice classification per grid cell -- also "
        "fixed, given as context (e.g. so the model can treat ocean and land "
        "surface temperature differently), not predicted.",
}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data-dir", type=Path, required=True)
    p.add_argument("--dataset-file", type=str,
                    default="source-era5_date-2019-03-29_res-1.0_levels-13_steps-30.nc")
    p.add_argument("--predictions", type=Path, required=True)
    p.add_argument("--stats-dir", type=Path, default=None)
    p.add_argument("--report", type=Path, default=Path("./variable_inventory_report.txt"))
    return p.parse_args()


def describe_dataset(ds, name: str, lines: list[str]):
    lines.append(f"\n=== {name} ===")
    lines.append(f"Dimensions: {dict(ds.sizes)}")
    lines.append(f"{len(ds.data_vars)} data variables:")
    for var in sorted(ds.data_vars):
        da = ds[var]
        lines.append(f"  - {var:35s} dims={da.dims} shape={da.shape} dtype={da.dtype}")
    return ds


def main() -> None:
    args = parse_args()
    import xarray

    lines: list[str] = []
    lines.append("Empirical variable inventory -- generated by list_dataset_variables.py")

    dataset_path = args.data_dir / "dataset" / args.dataset_file
    stats_dir = args.stats_dir or (args.data_dir / "stats")

    example_batch = xarray.open_dataset(dataset_path, decode_timedelta=True)
    describe_dataset(example_batch, f"Source ERA5 dataset ({dataset_path.name})", lines)

    predictions = xarray.open_dataset(args.predictions)
    describe_dataset(predictions, f"predictions.nc ({args.predictions})", lines)

    lines.append("\n=== stats/ folder (normalization / climatology-like files) ===")
    if stats_dir.exists():
        for fpath in sorted(stats_dir.glob("*.nc")):
            try:
                sds = xarray.open_dataset(fpath)
                describe_dataset(sds, fpath.name, lines)
                has_spatial = "lat" in sds.dims or "lat" in sds.coords
                lines.append(f"  --> spatially resolved (has lat/lon)? {has_spatial}")
            except Exception as e:  # noqa: BLE001
                lines.append(f"  Could not open {fpath.name}: {e}")
    else:
        lines.append(f"  (no stats/ directory found at {stats_dir})")

    # Cross-reference predictions.nc's variables against what's already scored.
    pred_vars = set(predictions.data_vars)
    surface_leftover = pred_vars - ALREADY_SCORED_SURFACE
    atmos_vars_in_pred = {v for v in pred_vars if "level" in predictions[v].dims}
    surface_vars_in_pred = pred_vars - atmos_vars_in_pred
    unscored_surface = surface_vars_in_pred - ALREADY_SCORED_SURFACE
    unscored_atmos = atmos_vars_in_pred - ALREADY_SCORED_ATMOSPHERIC

    lines.append("\n=== Cross-check: anything in predictions.nc NOT already scored? ===")
    lines.append(f"Surface-type variables found in predictions.nc: {sorted(surface_vars_in_pred)}")
    lines.append(f"Atmospheric (per-level) variables found in predictions.nc: {sorted(atmos_vars_in_pred)}")
    if not unscored_surface and not unscored_atmos:
        lines.append(
            "RESULT: every variable in predictions.nc is already covered by "
            "evaluate_predictions.py (10 headline vars) and evaluate_full_scorecard.py "
            "(Tier 1 + Tier 2, 84 combinations total). Nothing left over."
        )
    else:
        lines.append("RESULT: found variables NOT currently scored anywhere:")
        for v in sorted(unscored_surface):
            lines.append(f"  - surface: {v}")
        for v in sorted(unscored_atmos):
            lines.append(f"  - atmospheric (per-level): {v}")

    lines.append("\n=== Known input-only variables (forcings) -- never appear in predictions.nc ===")
    lines.append("These condition the model as known future inputs; they are not forecast targets,")
    lines.append("so their absence from predictions.nc is expected, not a gap:")
    for v, desc in KNOWN_FORCING_VARS.items():
        present = v in example_batch.data_vars
        lines.append(f"  - {v} (present in source dataset: {present}): {desc}")

    lines.append("\n=== Known static input variables -- also never appear in predictions.nc ===")
    for v, desc in KNOWN_STATIC_VARS.items():
        present = v in example_batch.data_vars
        lines.append(f"  - {v} (present in source dataset: {present}): {desc}")

    report_text = "\n".join(lines)
    args.report.write_text(report_text)
    print(report_text)
    print(f"\nWrote {args.report}")


if __name__ == "__main__":
    main()
